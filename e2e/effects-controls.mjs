import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs'

const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
p.on('pageerror', e => errors.push(e.message))
const E = (fn, arg) => p.evaluate(fn, arg)
const px = (x, y) => E(async ([x, y]) => (await window.__vcPixels({ x, y, w: 1, h: 1 })).slice(0, 3), [x, y])
try {
  await p.goto(`${process.env.BASE || 'http://localhost:3123'}/editor`)
  await p.waitForFunction(() => !!window.__vcFx)
  const id = await E(() => {
    const s = window.__voidEditor.getState()
    s.newDoc({ name: 'Effects control QA', width: 200, height: 200, background: '#ffffff' })
    const id = window.__voidEditor.getState().addShape('rect', 0, 0, 200, 200, { fill: '#ffffff', name: 'Gradient target' })
    window.__voidUi.getState().showPanel('properties')
    return id
  })
  const put = kind => E(([id, kind]) => {
    window.__voidEditor.getState().updateLayer(id, { styles: { order: ['gradientOverlay'], gradientOverlay: { on: true, opacity: 1, blend: 'source-over', from: '#000000', to: '#ffffff', angle: 0, scale: 100, kind } } }, `Gradient ${kind}`)
  }, [id, kind])
  await put('linear')
  assert((await px(5, 100))[0] < 15 && (await px(195, 100))[0] > 240)
  await put('radial')
  assert((await px(100, 100))[0] < 8)
  const right = (await px(150, 100))[0], down = (await px(100, 150))[0]
  assert(Math.abs(right - down) < 4, 'Radial must be circular')
  await put('reflected')
  assert(Math.abs((await px(50, 100))[0] - (await px(150, 100))[0]) < 4)
  await put('diamond')
  assert((await px(150, 150))[0] > (await px(150, 100))[0] + 60)
  await put('angle')
  assert((await px(100, 150))[0] < (await px(100, 50))[0])
  for (const kind of ['linear', 'radial', 'angle', 'reflected', 'diamond']) {
    await put(kind)
    const parity = await E(() => window.__vcParity({ scale: 0.5 }))
    assert(parity.mean < 3, `${kind} preview/export parity: ${parity.mean}`)
  }
  await put('radial')
  await E(id => window.__voidEditor.getState().updateLayer(id, { styles: { ...window.__voidEditor.getState().active().styles, gradientOverlay: { ...window.__voidEditor.getState().active().styles.gradientOverlay, reverse: true, stops: [{ position: 0, color: '#000000' }, { position: 0.5, color: '#ff0000' }, { position: 1, color: '#ffffff' }] } } }, 'Reverse stops'), id)
  assert((await px(100, 100))[0] > 245)
  await E(() => window.__voidEditor.getState().undo())
  assert((await px(100, 100))[0] < 8)
  await E(() => window.__voidEditor.getState().redo())
  assert((await px(100, 100))[0] > 245)
  await E(() => window.dispatchEvent(new CustomEvent('vc:open', { detail: { name: 'layerStyle', props: { focus: 'gradientOverlay' } } })))
  await p.getByLabel('Gradient type', { exact: true }).selectOption('diamond')
  assert.equal(await E(() => window.__voidEditor.getState().active().styles.gradientOverlay.kind), 'diamond')
  await p.getByText('Placement and shape', { exact: true }).click()
  await p.getByRole('spinbutton', { name: 'Scale value', exact: true }).fill('75')
  await p.getByRole('spinbutton', { name: 'Scale value', exact: true }).press('Tab')
  const slider = await p.getByRole('slider', { name: 'Scale', exact: true }).evaluate(el => {
    const track = el.parentElement.getBoundingClientRect(), rect = el.getBoundingClientRect()
    const thumb = getComputedStyle(el, '::-webkit-slider-thumb'), rail = getComputedStyle(el, '::-webkit-slider-runnable-track')
    return { height: rect.height, offset: rect.y - track.y, thumb: Number.parseFloat(thumb.height), rail: Number.parseFloat(rail.height), margin: Number.parseFloat(thumb.marginTop) }
  })
  assert.equal(slider.height, 16); assert.equal(slider.offset, 0)
  assert.equal(slider.margin, (slider.rail - slider.thumb) / 2)
  fs.mkdirSync('e2e/.out', { recursive: true })
  await p.screenshot({ path: 'e2e/.out/gradient-controls.png' })
  await p.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal(await E(() => window.__voidEditor.getState().active().styles.gradientOverlay.kind), 'radial')
  await E(() => {
    const s = window.__voidEditor.getState(), fx = window.__vcFx.newEffect('blur')
    fx.values = { radius: 20, mode: 1, angle: 45, strength: 50 }
    s.addEffect([{ type: 'layer', id: s.activeId }], fx, 'Motion blur')
  })
  await p.getByLabel('Blur type', { exact: true }).selectOption('2')
  await p.getByText('Blur centre', { exact: true }).click()
  await p.getByRole('spinbutton', { name: 'Centre X value', exact: true }).fill('35')
  await p.getByRole('spinbutton', { name: 'Centre X value', exact: true }).press('Tab')
  assert.equal(await E(() => window.__voidEditor.getState().active().effects[0].values.centerX), 35)
  await E(() => window.__vcSave.flush())
  await p.reload(); await p.waitForFunction(() => !!window.__voidEditor?.getState().active()?.effects?.length)
  assert.equal(await E(() => window.__voidEditor.getState().active().effects[0].values.centerX), 35)
  assert.equal(await E(() => window.__voidEditor.getState().active().styles.gradientOverlay.reverse), true)
  await E(() => {
    const s = window.__voidEditor.getState(), fx = window.__vcFx.newEffect('voidEffect', 'invert')
    s.addEffect([{ type: 'layer', id: s.activeId }], fx, 'Invert')
  })
  await p.getByText('Finish · tone and colour', { exact: true }).click()
  await p.getByRole('spinbutton', { name: 'Finish brightness value', exact: true }).fill('25')
  await p.getByRole('spinbutton', { name: 'Finish brightness value', exact: true }).press('Tab')
  assert.equal(await E(() => window.__voidEditor.getState().active().effects[1].effectParams.finishBrightness), 25)
  const parity = await E(() => window.__vcParity({ scale: 0.5 }))
  assert(parity.mean < 4, `Blur/finish preview-export parity: ${parity.mean}`)
  const layerCount = await E(() => window.__voidEditor.getState().layers.length)
  await E(() => window.__voidUi.getState().closePanel('properties'))
  await p.getByRole('menuitem', { name: 'Filter', exact: true }).click()
  await p.getByRole('menuitem', { name: 'Enhance', exact: true }).hover()
  await p.getByRole('menuitem', { name: 'Sharpen', exact: true }).click()
  await p.getByRole('slider', { name: 'Amount', exact: true }).waitFor()
  assert.equal(await E(() => window.__voidEditor.getState().layers.length), layerCount)
  assert.equal(await E(() => window.__voidEditor.getState().active().effects[2].effect), 'sharpen')
  assert.equal(await E(() => !!document.querySelector('[data-nextjs-dialog]')), false)
  assert.deepEqual(errors, [])
  console.log('PASS: five gradient pixel checks and export parity, reverse/stops, undo/redo, controls, exact values, slider geometry, cancel, blur modes, save/reload, filter finishing, menu target and settings discovery, no page errors')
} finally { await b.close() }
